import numpy as np
import matplotlib.pyplot as plt
import tensorflow as tf
import cv2
from tensorflow.keras.preprocessing.image import load_img, img_to_array

IMG_SIZE = 224

def grad_cam_plus_plus(model, img, layer_name='top_conv'):
    grad_model = tf.keras.models.Model([model.inputs], [model.get_layer(layer_name).output, model.output])
    with tf.GradientTape() as tape:
        inputs = tf.cast(img, tf.float32)
        conv_outputs, predictions = grad_model(inputs)
        loss = predictions[:, tf.argmax(predictions[0])]
    grads = tape.gradient(loss, conv_outputs)[0]
    alpha_num = grads ** 2
    alpha_denom = 2 * grads ** 2 + tf.reduce_sum(conv_outputs[0] * grads, axis=(0, 1)) + 1e-10
    alphas = alpha_num / alpha_denom
    weights = tf.reduce_sum(alphas * tf.nn.relu(grads), axis=(0, 1))
    cam = np.zeros(conv_outputs.shape[1:3], dtype=np.float32)
    conv_outputs = conv_outputs[0]
    for i, w in enumerate(weights):
        cam += w * conv_outputs[:, :, i]
    cam = cv2.resize(cam.numpy(), (IMG_SIZE, IMG_SIZE))
    cam = np.maximum(cam, 0)
    cam = cam / (cam.max() + 1e-10)
    return cam

def plot_gradcam_with_box(img_path, model, layer_name='top_conv', alpha=0.5, threshold=0.6, pad=15):
    img = load_img(img_path, target_size=(IMG_SIZE, IMG_SIZE))
    img_arr = img_to_array(img).astype(np.uint8)
    img_input = img_arr / 255.0
    img_input = np.expand_dims(img_input, axis=0)
    cam = grad_cam_plus_plus(model, img_input, layer_name)

    # Overlay heatmap
    plt.figure(figsize=(6, 6))
    plt.imshow(img_arr, cmap='gray')
    plt.imshow(cam, cmap='jet', alpha=alpha)

    # Find and draw bigger box on hottest region
    binary_mask = (cam > threshold * cam.max()).astype(np.uint8)
    contours, _ = cv2.findContours(binary_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    if contours:
        biggest = max(contours, key=cv2.contourArea)
        x, y, w, h = cv2.boundingRect(biggest)
        # Expand box by 'pad' pixels on each side
        x_new = max(x - pad, 0)
        y_new = max(y - pad, 0)
        w_new = min(w + 2*pad, IMG_SIZE - x_new)
        h_new = min(h + 2*pad, IMG_SIZE - y_new)
        plt.gca().add_patch(
            plt.Rectangle((x_new, y_new), w_new, h_new, linewidth=2.5, edgecolor='yellow', facecolor='none')
        )
    plt.axis('off')
    plt.title('Tumor Image - Grad-CAM++')
    plt.tight_layout()
    plt.show()


    for i in range(9):
        plt.subplot(3, 3, i + 1)
        plt.imshow(images[i])
        pred_label = "Tumor" if predictions[i][0] > 0.5 else "Non Tumor"
        true_label = "Tumor" if labels[i] == 1 else "Non Tumor"
        plt.title(f"True: {true_label}, Pred: {pred_label}", fontsize=10)
        plt.axis('off')
    plt.tight_layout()
    plt.show()


# --- 1. Define ROI Crop Function ---
def crop_brain_contour(image, plot=False):
    if image is None:
        return None
    img = image.copy()
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    blurred = cv2.GaussianBlur(gray, (5, 5), 0)
    _, thresh = cv2.threshold(blurred, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)
    contours, _ = cv2.findContours(thresh, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    if len(contours) == 0:
        return None
    largest_contour = max(contours, key=cv2.contourArea)
    x, y, w, h = cv2.boundingRect(largest_contour)
    new_img = img[y:y+h, x:x+w]
    if plot:
        img_cnt = img.copy()
        cv2.drawContours(img_cnt, [largest_contour], 0, (0, 255, 0), 2)
        img_pnt = img.copy()
        cv2.rectangle(img_pnt, (x, y), (x + w, y + h), (0, 255, 0), 2)
        plt.figure(figsize=(15, 6))
        plt.subplot(141)
        plt.imshow(cv2.cvtColor(img, cv2.COLOR_BGR2RGB)); plt.xticks([]); plt.yticks([]); plt.title('Original')
        plt.subplot(142)
        plt.imshow(cv2.cvtColor(img_cnt, cv2.COLOR_BGR2RGB)); plt.xticks([]); plt.yticks([]); plt.title('Contour')
        plt.subplot(143)
        plt.imshow(cv2.cvtColor(img_pnt, cv2.COLOR_BGR2RGB)); plt.xticks([]); plt.yticks([]); plt.title('Bounding Box')
        plt.subplot(144)
        plt.imshow(cv2.cvtColor(new_img, cv2.COLOR_BGR2RGB)); plt.xticks([]); plt.yticks([]); plt.title('Cropped')
        plt.show()
    return new_img


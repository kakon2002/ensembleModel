def augment_image(img):
    out = []
    out.append((img, "Original"))
    out.append((rotate_image(img, angle=20), "Rotated +20°"))
    out.append((rotate_image(img, angle=-20), "Rotated -20°"))
    out.append((flip_horizontal(img), "Flipped Horiz"))
    out.append((increase_brightness(img), "Brightness +"))
    out.append((decrease_brightness(img), "Brightness -"))
    out.append((zoom_in(img), "Zoomed In"))
    return out

# --- 3. Batch Crop ROI for a Dataset ---
def preprocess_and_crop_dataset(X):
    IMG_SIZE = 224
    X_cropped = []
    for img in tqdm(X, desc="Cropping ROIs"):
        img = (img * 255).astype(np.uint8) if img.max() <= 1.0 else img.astype(np.uint8)
        if img.ndim == 2:
            img = np.stack([img]*3, axis=-1)
        elif img.shape[2] == 1:
            img = np.concatenate([img]*3, axis=-1)
        cropped = crop_brain_contour(img, plot=False)
        if cropped is not None:
            cropped = cv2.resize(cropped, (IMG_SIZE, IMG_SIZE))
        else:
            cropped = cv2.resize(img, (IMG_SIZE, IMG_SIZE))
        X_cropped.append(cropped.astype(np.float32) / 255.0)
    return np.array(X_cropped)

